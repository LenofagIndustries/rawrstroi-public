gmlfi.ValueToString = function(v, ...) local t = types[type(v)] return t and t(v, ...) or tostring(v) end

TableToString = function(c, mdepth, depth) depth = depth or 1
    local str, seq = {}, {}
    for k, v in ipairs(c) do
        seq[k] = true
        local t = types[type(v)]
        str[k] = t and t(v, mdepth, depth + 1) or ("\"" .. tostring(v) .. "\"")
    end
    for k, v in pairs(c) do
        if not seq[k] then
            local t = types[type(v)]
            local t2 = types[type(k)]
            str[#str + 1] = string.format("[%s] = %s", t2 and t2(k, mdepth, depth + 1) or tostring(k), t and t(v, mdepth, depth + 1) or tostring(v))
        end
    end

    local ts = string.rep("    ", depth)
    return "{\n" .. ts .. table.concat(str, ",\n" .. ts) .. "\n" .. string.rep("    ", depth - 1) .. "}"
end

gmlfi.TableToString = TableToString