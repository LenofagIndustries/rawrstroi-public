local fsnsx = {
    ["Цейтлин"] = true,
    ["Бейкон"] = true,
}

local fsnda = function(s, sn)
    if not s and not fsnsx[sn] then
        local ss = utf8.sub(sn, -1)
        if ss == "в" or ss == "н" then sn = sn .. "а" end
        sn = sn:gsub("ый$", "ая"):gsub("ий$", "ая"):gsub("ой$", "ая")
    end
    return sn
end

gmlfi.RandomName = function()
    local s = gmlfi.RandomBool()
    local n = s and mnames or fnames
    local sn = surnames[math.random(#surnames)]
    sn = fsnda(s, sn)
    if math.random() < .1 then sn = sn .. "-" .. fsnda(s, surnames[math.random(#surnames)]) end
    local ns = string.format("%s %s", n[math.random(#n)], sn)
    return math.random() < .1 and gmlfi.Transliterate(ns) or ns
end
gmlfi.RandomNames = function(num)
    local ret = {}
    if not num or num < 1 then return ret end

    for k = 1, num do
        ret[#ret + 1] = gmlfi.RandomName()
    end
    return ret
end

